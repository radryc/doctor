function endpointIcon(type: string) {
  if (type === "pagerduty") return <Radio size={14} />;
  if (type === "slack") return <Mail size={14} />;
  return <Webhook size={14} />;
}

function parseDraggedRule(event: React.DragEvent<HTMLElement>): DraggedRule | null {
  const raw = event.dataTransfer.getData("application/x-sentinel-rule");
  if (!raw) return null;
  try {
    const parsed = JSON.parse(raw) as Partial<DraggedRule>;
    if (!parsed.group || !parsed.alert) return null;
    return { kind: "rule", group: parsed.group, alert: parsed.alert };
  } catch {
    return null;
  }
}

function parseDraggedSource(event: React.DragEvent<HTMLElement>): DraggedSource | null {
  const raw = event.dataTransfer.getData("application/x-sentinel-source");
  if (!raw) return null;
  try {
    const parsed = JSON.parse(raw) as Partial<DraggedSource>;
    if (!parsed.source || !parsed.alert) return null;
    return { kind: "source", source: parsed.source, alert: parsed.alert };
  } catch {
    return null;
  }
}

function parseDragged(event: React.DragEvent<HTMLElement>): DraggedItem | null {
  return parseDraggedRule(event) ?? parseDraggedSource(event);
}

function severityBadgeClass(severity: string): string {
  switch (severity.toLowerCase()) {
    case "critical":
      return "border-rose-500/40 bg-rose-500/10 text-rose-300";
    case "warning":
      return "border-amber-500/40 bg-amber-500/10 text-amber-300";
    case "info":
      return "border-sky-500/40 bg-sky-500/10 text-sky-300";
    default:
      return "border-slate-600 bg-slate-800/70 text-slate-300";
  }
}

