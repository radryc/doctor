interface RoutingBoardProps {
  tenant: string;
  partition: string;
  config: ReceiverConfig;
  groups: AlertRuleGroupSummary[];
  alerts: Alert[];
  caps: Capabilities | null;
  canWrite: boolean;
  onReload: () => Promise<void>;
  onNotice: (message: string) => void;
  onError: (message: string) => void;
}

interface EndpointDraft {
  index: number | null;
  receiver: Receiver;
}

interface DraggedRule {
  kind: "rule";
  group: string;
  alert: string;
}

interface DraggedSource {
  kind: "source";
  source: string;
  alert: string;
}

type DraggedItem = DraggedRule | DraggedSource;

interface SourceAlertCard {
  source: string;
  alert: string;
  severity: string;
  description: string;
}

